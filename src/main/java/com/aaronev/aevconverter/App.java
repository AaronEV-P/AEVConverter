package com.aaronev.aevconverter;

import javafx.application.Application;
import javafx.fxml.FXMLLoader;
import javafx.scene.Parent;
import javafx.scene.Scene;
import javafx.stage.Stage;

import java.io.IOException;
import java.net.URL;
import java.util.logging.Logger;
import javafx.scene.image.Image;
import com.aaronev.aevconverter.ui.Dialogs;
import com.aaronev.aevconverter.update.UpdateChecker;

import javafx.application.Platform;

import java.io.InputStream;
import java.util.Properties;
import java.util.logging.Level;

/**
 * JavaFX App
 */
public class App extends Application {

    private static Scene scene;
    private static final Logger LOG = Logger.getLogger(App.class.getName());

    @Override
    public void start(Stage stage) throws IOException {
        configureLogging();
        scene = new Scene(loadFXML("ui/shell/mainShell"), 800, 500);

        // Set the application window icon
        stage.getIcons().add(new Image(App.class.getResourceAsStream("icons/icon_logo.png")));
        stage.setMinWidth(600);
        stage.setMinHeight(450);
        stage.setTitle("AEVConverter");
        stage.setScene(scene);
        stage.show();
        checkForUpdates(stage);
    }

    /**
     * Initializes application logging
     */
    private void configureLogging() {
        try {
            LogConfiguration.configure();
        } catch (IOException e) {
            System.err.println(
                    "Failed to initialize application logging.");
            e.printStackTrace(System.err);
        }
    }

    static void setRoot(String fxml) throws IOException {
        scene.setRoot(loadFXML(fxml));
    }

    private static Parent loadFXML(String fxml) throws IOException {
        String resourcePath = fxml + ".fxml";
        URL resource = App.class.getResource(resourcePath);

        if (resource == null) {
            throw new IOException(
                    "FXML resource not found on the classpath: " + resourcePath);
        }

        return new FXMLLoader(resource).load();
    }

    // Checks for application updates after the main window is displayed. 
    private void checkForUpdates(Stage stage) {

        final String currentVersion;

        try {
            currentVersion = loadApplicationVersion();
        } catch (IOException exception) {
            LOG.log(Level.FINE,
                    "Could not load the application version.",
                    exception);
            return;
        }

        UpdateChecker.checkForUpdates(currentVersion)
                .thenAccept(update -> update.ifPresent(info
                        -> Platform.runLater(() -> {

                            if (!stage.isShowing()) {
                                return;
                            }

                            boolean openRelease
                                    = Dialogs.showUpdateAvailable(
                                            info.currentVersion(),
                                            info.version());

                            if (openRelease) {
                                getHostServices().showDocument(
                                        info.releaseUrl());
                            }
                        })));
    }

    // Reads the application version generated by Maven.
    private static String loadApplicationVersion() throws IOException {

        Properties properties = new Properties();

        try (InputStream input
                = App.class.getResourceAsStream("/app.properties")) {

            if (input == null) {
                throw new IOException(
                        "Application properties file not found.");
            }

            properties.load(input);
        }

        String version = properties.getProperty("app.version");

        if (version == null || version.isBlank()) {
            throw new IOException(
                    "Application version is missing.");
        }

        return version.trim();
    }

    public static void main(String[] args) {
        launch();
    }

}
